void	load_font(t_Chip8 *chip8)
{
	int 			index;
	const uint8_t	fontset[5 * 16] = {
		0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
		0x20, 0x60, 0x20, 0x20, 0x70, // 1
		0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
		0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
		0x90, 0x90, 0xF0, 0x10, 0x10, // 4
		0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
		0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
		0xF0, 0x10, 0x20, 0x40, 0x40, // 7
		0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
		0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
		0xF0, 0x90, 0xF0, 0x90, 0x90, // A
		0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
		0xF0, 0x80, 0x80, 0x80, 0xF0, // C
		0xE0, 0x90, 0x90, 0x90, 0xE0, // D
		0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
		0xF0, 0x80, 0xF0, 0x80, 0x80  // F
	};

	index = 0;
	while (index < 5 * 16)
	{
		chip8->memory[index] = fontset[index];
		index++;
	}

	return ;
}

uint8_t	load_rom(char *filename, t_Chip8 *chip8)
{
	uint8_t	*rom;
	int		index;

	rom = get_file_content(filename, chip8);
	if (rom == NULL)
		return (1);
	
	index = 0;
	while (rom[index] != '\0')
	{
		chip8->memory[index + 200] = rom[index];
		index++;
	}
	return (0);
}

t_nibble	load_nibble(uint16_t opcode)
{
	t_nibble	nibble;

	nibble.opcode = opcode;
	nibble.t = opcode >> 12;
	nibble.x = opcode >> 8 & 0xF;
	nibble.y = opcode >> 4 & 0xF;
	nibble.n = opcode & 0xF;
	nibble.nn = opcode & 0xFF;
	nibble.nnn = opcode & 0xFFF;
	return (nibble);
}

t_nibble	fetch_nibble(uint16_t pc, uint8_t memory[MEMORY_SIZE])
{
	uint16_t opcode;

	opcode = (memory[pc] << 8) + memory[pc + 1];
	return load_nibble(opcode);
}
